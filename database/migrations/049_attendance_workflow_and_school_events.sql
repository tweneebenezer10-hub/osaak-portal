CREATE TABLE IF NOT EXISTS school_calendar_events (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    school_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(180) NOT NULL,
    category VARCHAR(40) NOT NULL DEFAULT 'other',
    description TEXT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    starts_at TIME NULL,
    ends_at TIME NULL,
    is_all_day TINYINT(1) NOT NULL DEFAULT 1,
    venue VARCHAR(180) NULL,
    audience ENUM('school','students','parents','teaching_staff','all_staff','selected_class') NOT NULL DEFAULT 'school',
    class_id BIGINT UNSIGNED NULL,
    status ENUM('draft','published','cancelled') NOT NULL DEFAULT 'draft',
    reminder_minutes SMALLINT UNSIGNED NULL,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    cancelled_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY idx_school_calendar_event_range (school_id, status, starts_on, ends_on),
    KEY idx_school_calendar_event_audience (school_id, audience, class_id, status),
    CONSTRAINT fk_school_calendar_event_school FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE,
    CONSTRAINT fk_school_calendar_event_class FOREIGN KEY (class_id) REFERENCES school_classes(id) ON DELETE SET NULL,
    CONSTRAINT fk_school_calendar_event_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_school_calendar_event_updater FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_school_calendar_event_dates CHECK (ends_on >= starts_on),
    CONSTRAINT chk_school_calendar_event_times CHECK (is_all_day = 1 OR (starts_at IS NOT NULL AND ends_at IS NOT NULL AND (ends_on > starts_on OR ends_at >= starts_at)))
) ENGINE=InnoDB;