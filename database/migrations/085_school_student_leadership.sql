CREATE TABLE IF NOT EXISTS school_student_leadership_assignments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    school_id BIGINT UNSIGNED NOT NULL,
    student_id BIGINT UNSIGNED NOT NULL,
    class_id BIGINT UNSIGNED NULL,
    academic_year VARCHAR(30) NOT NULL,
    position_title VARCHAR(100) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NULL,
    status ENUM('active','ended') NOT NULL DEFAULT 'active',
    assigned_by BIGINT UNSIGNED NULL,
    ended_by BIGINT UNSIGNED NULL,
    end_reason VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_school_leadership_roster (school_id, academic_year, status, position_title),
    KEY idx_school_leadership_student_history (school_id, student_id, status, starts_on),
    KEY idx_school_leadership_class_roster (school_id, class_id, academic_year, status),
    CONSTRAINT fk_school_leadership_school FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE,
    CONSTRAINT fk_school_leadership_student FOREIGN KEY (student_id) REFERENCES school_students(id) ON DELETE RESTRICT,
    CONSTRAINT fk_school_leadership_class FOREIGN KEY (class_id) REFERENCES school_classes(id) ON DELETE SET NULL,
    CONSTRAINT fk_school_leadership_assigner FOREIGN KEY (assigned_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_school_leadership_ender FOREIGN KEY (ended_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
